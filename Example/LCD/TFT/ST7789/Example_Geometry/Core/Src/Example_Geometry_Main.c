#include "Example_Geometry_Main.h"

nui_driver_Typedef st7789_drv;
ST7789_Typedef ST7789;

void EXAMPLE_GEOMETRY_MAIN(void)
{
	
	st7789_drv.set_px=ST7789_SET_PX;
	st7789_drv.blit_color=ST7789_BLIT_COLOR;
	st7789_drv.clear_window=ST7789_CLEAR_WINDOW;
	st7789_drv.clear=ST7789_CLEAR;
	st7789_drv.blit_mono=ST7789_BLIT_MONO;
	
	NUI_REGISTER_Driver(&st7789_drv);
	ST7789_INIT(&ST7789, &hspi2);
	
	ST7789_CLEAR(&ST7789,NUI_COLOR_BLACK);
	
	NUI_GEOMETRY_DRAW_RECTANGLE(&ST7789,0,0,100,100,NUI_COLOR_CYAN);
	NUI_GEOMETRY_DRAW_FILL_RECTANGLE(&ST7789,200,0,100,100,NUI_COLOR_MAGENTA);
	NUI_GEOMETRY_DRAW_CIRCLE(&ST7789,50,170,50,NUI_COLOR_LIME);
	NUI_GEOMETRY_DRAW_FILL_CIRCLE(&ST7789,250,170,50,NUI_COLOR_WHITE);
	while(1)
	{
		
	}
}
